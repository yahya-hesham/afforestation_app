  @override
  Future<Map<String, dynamic>?> load(String path, Locale locale) async {
    final langCode = locale.languageCode.toLowerCase();

    // 1. First attempt: Load from rootBundle (assets/translations/xx.json)
    try {
      final jsonString = await rootBundle.loadString('$path/$langCode.json');
      final data = json.decode(jsonString);
      if (data is Map<String, dynamic> && data.isNotEmpty) {
        return data;
      }
    } catch (_) {
      // Asset not yet compiled into asset bundle or path mismatch
    }

    // 2. Second attempt with normalized path without trailing/leading slashes
    try {
      final cleanPath = path.replaceAll(RegExp(r'^/|/$'), '');
      final jsonString = await rootBundle.loadString('$cleanPath/$langCode.json');
      final data = json.decode(jsonString);
      if (data is Map<String, dynamic> && data.isNotEmpty) {
        return data;
      }
    } catch (_) {
      // Fall through to in-memory dictionary
    }

    // 3. Guaranteed fallback: Embedded in-memory translations
    if (langCode == 'en') {
      return embeddedEn;
    }
    return embeddedAr;
  }

